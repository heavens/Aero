
import * as fs from 'fs'
import * as Path from "path";
import { check } from 'reserved-words'
import xml2js from 'xml2js'
import toCamelCase from 'to-camel-case'

interface XML2NodeJs {
  path: {
    $: {
      d: string
      'fill-rule'?: string
    }
  }
}

interface OcticonProps {
  readonly jsFriendlyName: string;
  readonly pathData: string;
  readonly viewBox: string;
  readonly width: string;
  readonly height: string;
  readonly fillRule?: string;
}

const VIEWBOX_REGEX = /0 0 (\d+) (\d+)/

/**
 * Reads the passed-in string in XML format and translates it to our predefined structure.
 * @param xml The string contents, expected in XML format, to be parsed.
 * @returns A {@link XML2NodeJs} typed value representing the successful output, otherwise returning an error describing what went wrong.
 */
function parseXml(xml: string): Promise<XML2NodeJs> {
  return new Promise((resolve, reject) => {
    xml2js.parseString(xml, function (err, result: XML2NodeJs) {
      if (err) {
        reject(err)
      } else {
        resolve(result)
      }
    })
  })
}

/**
 * Normalizes the identifier for the generated Octicon name.
 * @param name
 * @returns
 */
function getJsFriendlyName(name: string) {
  // Mack: Should we allow capitlization of the first character (effectively turning camelCase to PascalCase)? There's a lot of
  // inconsistency in the JS/TS community when it comes to conventions... My better judgment wants to fallback to my
  // java origins of `SOME_VAR` formatting seeing as these are top-level, immutable constants.
  // Also do we really need a whole dependency for just this... :|
  const sanitizedName = toCamelCase(name);
  return check(sanitizedName, 'es6', true) ? sanitizedName + '_' : sanitizedName
}

/**
 * Takes the latest release of Octicons by @Primer and codegens typed structs to be used within tsx context.
 *
 * However, this may not really be even necessary to maintain anymore as the reason that initially warranted this task is not
 * as big of a concern.
 * @returns A promise for the code-generating task of Octicons.
 */
async function* generateIconData() {
  const octicons = await require('@primer/octicons');
  for (const name of Object.keys(octicons).sort()) {
    const octicon = octicons[name]

    if (octicon.heights.length === 0) {
      throw new Error(`Unexpected empty sizes array for ${octicon.symbol}`)
    }

    const octiconData = octicon.heights['16'] ?? octicon.heights[Object.keys(octicon.heights)[0]]
    const viewBox = octiconData.options.viewBox
    const viewBoxMatch = VIEWBOX_REGEX.exec(viewBox)
    if (!viewBoxMatch) {
      throw new Error(
        `Unexpected viewBox format for ${octicon.symbol} - '${viewBox}'`
      )
    }

    const [_, height] = viewBoxMatch;
    const width = height;
    const result = await parseXml(octiconData.path)
    const pathData = result.path.$.d
    const jsFriendlyName = getJsFriendlyName(octicon.symbol)
    const fillRule = result.path.$['fill-rule']

    yield {
      jsFriendlyName,
      width,
      height,
      viewBox,
      pathData,
      fillRule,
    } as OcticonProps;
  }
}

function writeIcon(stream: fs.WriteStream, icon: OcticonProps) {
  const { jsFriendlyName, pathData, width, height, viewBox, fillRule } = icon;
  stream.write(
    `export const ${jsFriendlyName}: OcticonSymbolType = { viewBox: \"${viewBox}\", w: ${width}, h: ${height}, d: '${pathData}', fr: ${fillRule ? `'${fillRule}'` : 'undefined'
    }}\n\n`
  )
}

/**
 * Runs the code-generation task.
 */
async function run() {
  const startTimestamp = Date.now();
  console.log("============================================================");
  console.log("|| Using latest @primer/octicons release                  ||");
  console.log("|| Starting octicon codegen                               ||");
  console.log("============================================================");
  const out = fs.createWriteStream(
    Path.resolve(__dirname, '../ui/src/components/octicon/octicons.ts'),
    {
      encoding: 'utf-8',
    }
  );

  out.write('/*\n');
  out.write(
    `DO NOT MODIFY THIS FILE MANUALLY.\nThis file was automatically generated by Aero on ${new Date().toDateString()}.\n`
  );
  out.write(' */\n\n')
  out.write(
    "export type OcticonSymbolType = { readonly viewBox: string; readonly w: number; readonly h: number; readonly d: string; readonly fr?: React.SVGAttributes<SVGElement>['fillRule']}\n\n"
  );

  for await (const data of generateIconData()) {
    writeIcon(out, data);
  }

  out.end();
  console.log(`Process took ${Date.now() - startTimestamp}ms.`);
}

run().catch(console.error);
