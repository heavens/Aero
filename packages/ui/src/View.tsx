import React from "react";
import { BehaviorSubject, Subscription } from "rxjs";
import { SubscriptionSet } from "./observable/subscription";

export abstract class View<P = {}, S = {}> extends React.Component<P, S> {
  /**
   * A name distinct to the view. 
   */
  name: string;
  
  /**
   * An identifier representing a distinct version of this view.
   */
  versionId: number;

  /**
   * The active set of subscriptions associated with this view. 
   */
  subscriptions: SubscriptionSet = new SubscriptionSet();

  /**
   * The model encapsulating the shared state.
   */
  private _model: S;

  /**
   * Emits whether the view has successfully unmounted from the UI. This will emit a value of `true` after
   * the `componentWillUnmount` function is invoked.
   */
  private unmounted: BehaviorSubject<boolean> = new BehaviorSubject<boolean>(false);

  /**
   * Returns the model serving as the active state for the view.
   */
  public get model(): S { 
    return this._model;
  }

  constructor(props: P) {
    super(props);
  }

  /**
   * Creates a new subscription from the passed-in observable.
   */
  public subscribe(func: () => Subscription) {
    this.subscriptions.push(func());
  }

  componentWillUnmount(): void {
    this.unmounted.next(true);
    this.dispose();
  }

  /**
   * Disposes of any underlying allocated resources generated by the view.
   */
  public dispose() {
    this.subscriptions.drain(sub => {
      sub.unsubscribe();
      return true;
    });
  }
}

